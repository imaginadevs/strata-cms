package events

import (
	"errors"

	"github.com/google/uuid"
)

// ErrForbidden lets a synchronous "before.*" handler reject an operation with
// a 403 instead of the default 400. Wrap it: fmt.Errorf("...: %w", events.ErrForbidden).
var ErrForbidden = errors.New("forbidden")

// EventType identifies what lifecycle point triggered the event.
type EventType string

const (
	// Data lifecycle
	EventBeforeCreate EventType = "items.before.create"
	EventAfterCreate  EventType = "items.after.create"
	EventBeforeRead   EventType = "items.before.read"
	EventAfterRead    EventType = "items.after.read"
	EventBeforeUpdate EventType = "items.before.update"
	EventAfterUpdate  EventType = "items.after.update"
	EventBeforeDelete EventType = "items.before.delete"
	EventAfterDelete  EventType = "items.after.delete"

	// Schema lifecycle
	EventCollectionCreated EventType = "schema.collection.created"
	EventCollectionUpdated EventType = "schema.collection.updated"
	EventCollectionDeleted EventType = "schema.collection.deleted"
	EventFieldCreated      EventType = "schema.field.created"
	EventFieldUpdated      EventType = "schema.field.updated"
	EventFieldDeleted      EventType = "schema.field.deleted"

	// Auth lifecycle
	EventUserLogin        EventType = "auth.login"
	EventUserLogout       EventType = "auth.logout"
	EventUserCreated      EventType = "auth.user.created"
	EventPasswordChanged  EventType = "auth.password.changed"
	EventTokenRefreshed   EventType = "auth.token.refreshed"

	// Tenant lifecycle
	EventTenantCreated EventType = "tenant.created"
	EventTenantUpdated EventType = "tenant.updated"

	// Auto-generation
	// Fired once per field after an auto-generate function computes a value.
	// Payload carries: "field" (string), "fn" (string), "value" (any).
	EventItemFieldAutoGenerated EventType = "items.field.auto_generated"

	// Notifications
	EventNotificationCreated EventType = "notification.created"
	EventNotificationRead    EventType = "notification.read"
)

// Event carries context about what happened and to which data.
type Event struct {
	Type       EventType      `json:"type"`
	Collection string         `json:"collection"`
	TenantID   uuid.UUID      `json:"tenant_id"`
	UserID     *uuid.UUID     `json:"user_id,omitempty"`
	UserEmail  string         `json:"user_email,omitempty"`
	ItemID     *string        `json:"item_id,omitempty"`
	Old        map[string]any `json:"old,omitempty"`
	Payload    map[string]any `json:"payload,omitempty"` // new/delta data
	Meta       map[string]any `json:"meta,omitempty"`    // request headers, IP, etc.
}
